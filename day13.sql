-- show me product name and category name


select p.ProductName,  c.CategoryName
from `e1.products` as p
join `e1.categories` as c
on p.CategoryID = c.CategoryID;


-- Display products belonging to the Electronics category.

select p.ProductName,  c.CategoryName
from `e1.products` as p
join `e1.categories` as c
on p.CategoryID = c.CategoryID
where c.CategoryName = "Electronics";


-- Display products with their category names, sorted by MRP from highest to lowest.
select p.ProductName,  c.CategoryName,p.MRP
from `e1.products` as p
join `e1.categories` as c
on p.CategoryID = c.CategoryID
order by p.MRP desc;



-- Display ProductName, CategoryName and discount amount.

select p.ProductName,  c.CategoryName,(p.MRP - p.SellingPrice) as discount
from `e1.products` as p
join `e1.categories` as c
on p.CategoryID = c.CategoryID
order by discount desc;


-- Display each product along with its supplier name and supplier state.

select p.ProductName,s.SupplierName,s.State
from `e1.products` as p
inner join `e1.suppliers` as s
on p.SupplierID = s.SupplierID;

-- Display all successful customer orders along with customer name and city.

select c.CustomerID,c.name,c.City
from `e1.orders` as o
inner join `e1.customers` as c
on o.CustomerID = c.CustomerID
where Status = "Cancelled";


-- Calculate total sales value for every order.


select o.OrderID, sum(oi.Total) as totalamt
from `e1.orders` as o
inner join `e1.order_items` as oi
on o.OrderID = oi.OrderID
group by o.OrderID
order by totalamt desc;


-- Calculate total sales value generated by each customer.


select 
  c.Name ,
 sum(oi.Total) as totalamt
from `e1.customers` as c
inner join `e1.orders` as o
on c.CustomerID = o.CustomerID
inner join `e1.order_items` as oi
on o.OrderID = oi.OrderID
group by c.CustomerID,c.Name
order by totalamt desc;