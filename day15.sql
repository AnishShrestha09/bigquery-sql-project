-- For every custome, calculate:

-- Customer ID
-- Customer name
-- Number of orders placed
-- Total amount paid through successful payments only

-- Display only customers whose successful payment amount is greater than ₹50,000.

-- Sort customers from highest to lowest successful payment amount.

select 
c.CustomerID,
c.Name,
count(distinct o.OrderID),
sum(p.Amount) as totalamount
from `e1.customers` as c
inner join `e1.orders` as o
on c.CustomerID = o.CustomerID
inner join `e1.payments` as p
on o.OrderID = p.OrderID
where p.Status = "Success"
group by 
  c.CustomerID,
  c.Name
having totalamount >50000
order by totalamount desc;


-- ProductID
-- ProductName
-- CategoryName
-- SupplierName
-- Number of times the product appeared in order items
-- Total quantity sold
-- Total sales value
-- Average selling price

-- Only include products where the total sales value is greater than ₹1,00,000.


select 
  p.ProductID,
  p.ProductName,
  c.CategoryName,
  s.SupplierName,
  count(oi.ProductID),
  sum(oi.Quantity) as totalqt,
  sum(oi.Total) as totalsalesamt,
  avg(oi.SellingPrice) as avgsellingp
from `e1.products` as p
inner join `e1.categories` as c
on p.CategoryID = c.CategoryID
inner join `e1.suppliers` as s
on p.SupplierID = s.SupplierID
inner join `e1.order_items` as oi
on p.ProductID = oi.ProductID
group by 
  p.ProductID,
  p.ProductName,
  c.CategoryName,
  s.SupplierName
having totalsalesamt > 100000 
order by totalsalesamt desc;



-- Consider only products having an MRP greater than ₹20,000.

-- For every category, calculate:

-- CategoryID
-- CategoryName
-- Number of qualifying products
-- Average MRP of qualifying products
-- Maximum MRP
-- Minimum MRP

-- Display only categories having more than 2 qualifying products.

-- Sort by average MRP from highest to lowest.



select 
  c.CategoryID,
  c.CategoryName,
  count(p.ProductID) as totalproduct,
  round(avg(p.MRP),2) as avgprice,
  max(p.MRP) as max_price,
  min(p.MRP) as min_price
from `e1.categories` as c
inner join `e1.products` as p
on c.CategoryID = p.CategoryID
where p.MRP > 2000
group by 
  c.CategoryID,
  c.CategoryName
having totalproduct > 2
order by avgprice desc;


-- Find all customers who have never placed an order.

-- Display:

-- Customer ID
-- Customer name
-- City
-- Sort the result alphabetically by customer name.


select 
c.CustomerID,
c.Name,
c.City
from `e1.customers` as c
left join `e1.orders` as o
on c.CustomerID = o.CustomerID
where o.CustomerID is null
order by c.name ;


-- For every supplier, calculate:

-- SupplierID
-- SupplierName
-- Number of products supplied
-- Average MRP of their products
-- Total sales generated by their products
-- Total quantity sold

-- Include suppliers even if their products have never been sold.

-- For suppliers with no sales, display the sales and quantity as 0.

-- Sort suppliers by total sales from highest to lowest.



select 
  s.SupplierID,
  s.SupplierName,
  count(p.ProductID) as total_prod,
  COALESCE( avg(p.MRP),0) as avgmrp,
  COALESCE(SUM(o.Total), 0) AS totalsales,
  COALESCE(SUM(o.Quantity), 0) AS totalqtsld
from `e1.suppliers` as s
left join `e1.products` as p
on s.SupplierID = p.SupplierID
left  join `e1.order_items` as o
on p.ProductID = o.ProductID
group by 
  s.SupplierID,
  s.SupplierName
order by totalsales desc
