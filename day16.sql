-- For every warehouse, calculate:

-- WarehouseID
-- Warehouse name
-- Number of orders handled
-- Total quantity of products sold
-- Total sales value

-- Include warehouses even if they have no orders.

-- Display only warehouses where the total sales value is greater than <2,00,000.

-- Sort from highest to lowest total sales.

select * from `e1.orders`;

select 
w.WarehouseID,
w.Warehouse,
count(distinct o.OrderID) as totalorders,
sum(oi.Quantity) as totalquantity,
sum(oi.Total) as total_sale
from `e1.warehouse` as w
left join `e1.orders` as o
on w.WarehouseID = o.WarehouseID
left join `e1.order_items` as oi
on o.OrderID = oi.OrderID
group by 
w.WarehouseID,
w.Warehouse
having total_sale >200000
order by total_sale desc;


-- Calculate the total sales value generated by every customer.

-- Then display only those customers whose total spending is greater than the average customer spending.

-- Display:

-- Customer ID
-- Customer name
-- Total spending

-- Sort from highest spending to lowest.

select 
  c.CustomerID,
  c.name,
  sum(oi.Total) as total_amt
from `e1.customers` as c
inner join `e1.orders` as o
on c.CustomerID = o.CustomerID
inner join `e1.order_items` as oi
on o.OrderID = oi.OrderID
group by
  c.CustomerID,
  c.name
having total_amt > (select
 avg(total_amt) from
  ( select 
  c.CustomerID,
  c.name,
  sum(oi.Total) as total_amt
from `e1.customers` as c
inner join `e1.orders` as o
on c.CustomerID = o.CustomerID
inner join `e1.order_items` as oi
on o.OrderID = oi.OrderID
group by
  c.CustomerID,
  c.name

))
order by total_amt desc;


-- For every product, calculate its total sales value.

-- Display only products whose total sales value is greater than the average total sales value of products
-- belonging to the same category.

-- Display:

-- ProductID
-- ProductName
-- CategoryName
-- TotalSales

-- Sort by total sales from highest to lowest.
SELECT
    p.ProductID,
    p.ProductName,
    c.CategoryName,
    SUM(oi.Total) AS TotalSales

FROM `e1.products` AS p

INNER JOIN `e1.categories` AS c
    ON p.CategoryID = c.CategoryID

INNER JOIN `e1.order_items` AS oi
    ON p.ProductID = oi.ProductID

GROUP BY
    p.ProductID,
    p.ProductName,
    c.CategoryName,
    p.CategoryID

HAVING SUM(oi.Total) > (

    SELECT AVG(product_sales)

    FROM (
        SELECT
            p2.ProductID,
            SUM(oi2.Total) AS product_sales

        FROM `e1.products` AS p2

        INNER JOIN `e1.order_items` AS oi2
            ON p2.ProductID = oi2.ProductID

        WHERE p2.CategoryID = p.CategoryID

        GROUP BY p2.ProductID
    )

)

ORDER BY TotalSales DESC;


