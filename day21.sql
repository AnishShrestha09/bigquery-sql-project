-- Product name
-- Category
-- Quantity
-- Selling price
-- Total

select 
  c.CustomerID,
  c.Name,
  p.ProductID,
  p.ProductName,
  p.CategoryID,
  oi.SellingPrice,
  sum(oi.Quantity) as total_Quantity,
  sum(oi.Total) as total
